// Rasterises Press Start 2P (OFL) once at its native 8 px into a 1-bit
// bitmap atlas and writes src/render/fontAtlas.ts. The game then uses the
// fixed bitmap, so text looks the same on every OS and browser (no hinting
// or ClearType differences). Run: node scripts/font-atlas.mjs
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';

const CHARS =
  ' !"#$%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~' +
  'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ½°×←→↑↓★·▶ω';
const dir = 'node_modules/@fontsource/press-start-2p/files/';
const font = (f) => readFileSync(dir + f).toString('base64');

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<style>
@font-face { font-family: P; src: url(data:font/woff2;base64,${font('press-start-2p-latin-400-normal.woff2')}) format('woff2'); }
@font-face { font-family: P; src: url(data:font/woff2;base64,${font('press-start-2p-latin-ext-400-normal.woff2')}) format('woff2'); unicode-range: U+0100-024F; }
</style><span style="font-family:P">AąŁ</span>`);
const png = await page.evaluate(async (chars) => {
  await document.fonts.load('8px P', 'AąŁ½');
  await document.fonts.ready;
  const CELL = 8;
  const PER_ROW = 16;
  const list = [...chars];
  const c = document.createElement('canvas');
  c.width = PER_ROW * CELL;
  c.height = Math.ceil(list.length / PER_ROW) * CELL;
  const ctx = c.getContext('2d', { willReadFrequently: true });
  ctx.fillStyle = '#fcfcfc';
  ctx.textBaseline = 'top';
  ctx.font = '8px P';
  // symbols missing from the font, drawn by hand
  const maps = {
    '←': ['', '  #', ' ##', '#######', ' ##', '  #'],
    '→': ['', '    #', '    ##', '#######', '    ##', '    #'],
    '↑': ['   #', '  ###', ' #####', '   #', '   #', '   #', '   #'],
    '↓': ['   #', '   #', '   #', '   #', ' #####', '  ###', '   #'],
    '★': ['   #', '   #', '#######', ' #####', '  ###', ' ## ##', ' #   #'],
    '·': ['', '', '', '  ##', '  ##'],
    '▶': [' #', ' ##', ' ###', ' ####', ' ###', ' ##', ' #'],
    'ω': ['', '', '#    #', '#    #', '# ## #', '######', ' #  #'],
  };
  list.forEach((ch, i) => {
    const x = (i % PER_ROW) * CELL;
    const y = Math.floor(i / PER_ROW) * CELL;
    const m = maps[ch];
    if (m) m.forEach((r, j) => [...r].forEach((p, k) => p === '#' && ctx.fillRect(x + k, y + j, 1, 1)));
    else ctx.fillText(ch, x, y);
  });
  const img = ctx.getImageData(0, 0, c.width, c.height);
  for (let i = 0; i < img.data.length; i += 4) {
    const on = img.data[i + 3] >= 110;
    img.data[i] = img.data[i + 1] = img.data[i + 2] = 252;
    img.data[i + 3] = on ? 255 : 0;
  }
  ctx.putImageData(img, 0, 0);
  return c.toDataURL('image/png');
}, CHARS);
await browser.close();
writeFileSync(
  'src/render/fontAtlas.ts',
  `// Generated by scripts/font-atlas.mjs from Press Start 2P (SIL Open Font\n// License 1.1). 8x8 cells, 16 per row, 1-bit alpha. Do not edit by hand.\n\nexport const FONT_CHARS = ${JSON.stringify(CHARS)};\n\nexport const FONT_PNG =\n  '${png}';\n`,
);
writeFileSync(process.argv[2] ?? '/dev/null', Buffer.from(png.split(',')[1], 'base64'));
console.log('font atlas:', CHARS.length, 'glyphs');
